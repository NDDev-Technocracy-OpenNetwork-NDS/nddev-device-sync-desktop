#!/usr/bin/env python3
"""Generate the native bridge and en/ru localization from their canonical inputs."""
import argparse
import os
from pathlib import Path
import subprocess
import sys

root = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path.insert(0, str(root / 'packages/nds_native/tool'))
from prepare_native import build_environment
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()

def generated():
    paths = list((root / 'packages/nds_native/lib/src/rust').rglob('*.dart'))
    paths += list((root / 'packages/nds_ui/lib/l10n').glob('app_localizations*.dart'))
    paths += [root / 'packages/nds_native/rust/src/frb_generated.rs']
    return {path: path.read_bytes() for path in paths if path.exists()}

original = generated()
environment = build_environment()
environment['CARGO_BUILD_JOBS'] = '4'
completed = False
try:
    for path in (root / 'packages/nds_native/lib/src/rust').rglob('*.dart'):
        if b'@generated by `flutter_rust_bridge`' not in path.read_bytes()[:256]:
            raise SystemExit('Refuse to remove non-generated bridge source: ' + str(path))
        path.unlink()
    for command, cwd in [
        (['flutter_rust_bridge_codegen', 'generate'], root / 'packages/nds_native'),
        (['cargo', 'fmt'], root / 'packages/nds_native/rust'),
        (['flutter', 'gen-l10n'], root / 'packages/nds_ui'),
    ]:
        subprocess.run(command, cwd=cwd, env=environment, check=True, timeout=180)
    current = generated()
    completed = True
    if args.check and original != current:
        names = sorted(str(path.relative_to(root)) for path in original.keys() | current.keys()
                       if original.get(path) != current.get(path))
        raise SystemExit('Generated-source drift: ' + ', '.join(names))
finally:
    if args.check or not completed:
        for path in generated().keys() - original.keys():
            path.unlink()
        for path, content in original.items():
            path.write_bytes(content)
